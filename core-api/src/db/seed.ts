import dotenv from 'dotenv';
dotenv.config({ path: `.env.${process.env.NODE_ENV}` });

import { db } from './index';
import { users, tanks, devices, sensors, sensorConfig } from './schema';

function requireFirst<T>(rows: T[], label: string): T {
    const row = rows[0];
    if (!row) throw new Error(`Seed failed: no row returned for ${label}`);
    return row;
}

async function seed() {
    console.log('Seeding database...');

    const user = requireFirst(
        db.insert(users).values({
            externalId: null,
        }).returning().all(),
        'user'
    );
    console.log(`Created user: ${user.id}`);

    const tank = requireFirst(
        db.insert(tanks).values({
            userId: user.id,
            name: 'Main Tank',
            description: "Garrett's freshwater aquarium",
        }).returning().all(),
        'tank'
    );
    console.log(`Created tank: ${tank.id}`);

    const device = requireFirst(
        db.insert(devices).values({
            tankId: tank.id,
            macAddress: '004B1224C0D4',
            name: 'ESP32 Main Tank',
        }).returning().all(),
        'device'
    );
    console.log(`Created device: ${device.id}`);

    // Sensor IDs are generated by the firmware (SensorIdentity) and stored in
    // the ESP32's NVS, so they stay stable across reboots and reflashes.
    // Only the temperature sensor has notifications on by default. The others
    // get placeholder thresholds: the Android app currently requires non-null
    // min/max values on every sensor config.
    const sensorSeeds = [
        {
            model: 'DS18B20',
            romAddress: '63399cab37ff55532f3f0473a0192b62',
            displayName: 'Water Temperature',
            config: { notificationsEnabled: true, minValue: 22.0, maxValue: 28.0 },
        },
        {
            model: 'CQRSENYW001',
            romAddress: 'abf2ddb02054e4bacd46c6f71f06f828',
            displayName: 'Water Level',
            config: { notificationsEnabled: false, minValue: 0, maxValue: 1 },
        },
        {
            model: 'CQRSENTDS01',
            romAddress: '23d3661f06a873580819942e38735732',
            displayName: 'TDS',
            config: { notificationsEnabled: false, minValue: 50, maxValue: 400 },
        },
        {
            model: 'PHMETERV11',
            romAddress: '29b050eeebc2a4b3a5883ea48ccb3e73',
            displayName: 'pH',
            config: { notificationsEnabled: false, minValue: 6.5, maxValue: 7.5 },
        },
    ];

    for (const { config, ...sensorValues } of sensorSeeds) {
        const sensor = requireFirst(
            db.insert(sensors).values({
                deviceId: device.id,
                ...sensorValues,
            }).returning().all(),
            'sensor'
        );
        console.log(`Created sensor: ${sensor.id} (${sensor.displayName})`);

        db.insert(sensorConfig).values({
            sensorId: sensor.id,
            updateIntervalSeconds: 30,
            ...config,
        }).run();
        console.log(`Created sensorConfig for sensor: ${sensor.id}`);
    }

    console.log('Done.');
}

seed().catch(console.error);
